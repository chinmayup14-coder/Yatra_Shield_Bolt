const LANGUAGES_POOL = ['English', 'Hindi', 'Bengali', 'Tamil', 'Telugu', 'Marathi', 'Kannada', 'Gujarati', 'Punjabi', 'Malayalam', 'Urdu', 'Assamese', 'Spanish', 'French'];

const SPECIALTIES_POOL = ['Food', 'Religious', 'Historical', 'Nature', 'Photography', 'Shopping', 'Architecture', 'Wildlife', 'Adventure', 'Spiritual'];

function seedRandom(seed: number): () => number {
  let s = seed;
  return () => {
    s = (s * 9301 + 49297) % 233280;
    return s / 233280;
  };
}

function generateGuidesForPlace(placeName: string, count: number): MockGuide[] {
  const seed = placeName.split('').reduce((acc, c) => acc + c.charCodeAt(0), 0);
  const rand = seedRandom(seed);

  return Array.from({ length: count }, (_, i) => {
    const nameIdx = Math.floor(rand() * GUIDE_NAMES.length);
    const bioIdx = Math.floor(rand() * GUIDE_BIOS.length);
    const numLangs = 2 + Math.floor(rand() * 3);
    const numSpecs = 2 + Math.floor(rand() * 3);

    const langs = [...LANGUAGES_POOL]
      .sort(() => rand() - 0.5)
      .slice(0, numLangs);
    const specs = [...SPECIALTIES_POOL]
      .sort(() => rand() - 0.5)
      .slice(0, numSpecs);

    return {
      id: `${placeName}-${i}`,
      name: GUIDE_NAMES[nameIdx],
      rating: Math.round((3.8 + rand() * 1.2) * 10) / 10,
      reviews: 15 + Math.floor(rand() * 280),
      experienceYears: 1 + Math.floor(rand() * 18),
      languages: langs,
      specialties: specs,
      bio: GUIDE_BIOS[bioIdx],
      verified: rand() > 0.3,
      pricePerDay: 800 + Math.floor(rand() * 12) * 200,
    };
  }).sort((a, b) => b.rating - a.rating);
}

export function getGuidesForPlace(placeName: string, guideCount: number): MockGuide[] {
  const displayCount = Math.min(guideCount, 5);
  return generateGuidesForPlace(placeName, displayCount);
}

